pub fn is_known_property(prop: &str) -> bool {
    KNOWN_PROPERTIES.contains(&prop)
}

pub fn property_feature(prop: &str) -> Option<&'static str> {
    match prop {
        "display" | "flex-direction" | "justify-content" | "align-items" | "align-self" | "gap"
        | "flex-wrap" | "flex-grow" | "flex-shrink" => Some("flex"),
        "border-radius"
        | "border-top-left-radius"
        | "border-top-right-radius"
        | "border-bottom-right-radius"
        | "border-bottom-left-radius" => Some("radius"),
        "opacity" => Some("opacity"),
        "outline" | "outline-width" | "outline-color" | "outline-style" | "outline-offset" => {
            Some("outline")
        }
        "letter-spacing" => Some("text"),
        "text-shadow" => Some("textshadow"),
        "transform" | "transform-origin" => Some("transform"),
        "animation" | "animation-duration" => Some("animation"),
        "scrollbar-width"
        | "scrollbar-color"
        | "scrollbar-track-color"
        | "scrollbar-thumb-color"
        | "scrollbar-border-radius"
        | "scroll-behavior" => Some("scrollbar"),
        "position" | "top" | "right" | "bottom" | "left" | "z-index" => Some("positioning"),
        _ => None,
    }
}
